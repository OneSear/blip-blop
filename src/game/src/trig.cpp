int sine1024(int degrees) noexcept {
    return kSine[degrees];
}

int cosine1024(int degrees) noexcept {
    return kSine[(degrees + 90) % 360];
}

int squareRoot(int n) noexcept {
    if (n <= 0) {
        return 0;
    }
    // Bit by bit, from the highest power of 4 not above n.
    unsigned int rest = static_cast<unsigned int>(n);
    unsigned int root = 0;
    unsigned int bit = 1u << 30;
    while (bit > rest) {
        bit >>= 2;
    }
    while (bit != 0) {
        if (rest >= root + bit) {
            rest -= root + bit;
            root = (root >> 1) + bit;
        } else {
            root >>= 1;
        }
        bit >>= 2;
    }
    return static_cast<int>(root);
}

