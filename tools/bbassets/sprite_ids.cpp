bool isIdentifier(const std::string& s) {
    if (s.empty() || !std::islower(static_cast<unsigned char>(s[0]))) {
        return false;
    }
    for (const char c : s) {
        if (!std::islower(static_cast<unsigned char>(c)) && !std::isdigit(static_cast<unsigned char>(c)) &&
            c != '_') {
            return false;
        }
    }
    return s.back() != '_' && s.find("__") == std::string::npos;
}

// weapon_smg -> kWeaponSmg
std::string constantName(const std::string& name) {
    std::string out = "k";
    bool upper = true;
    for (const char c : name) {
        if (c == '_') {
            upper = true;
            continue;
        }
        out.push_back(upper ? static_cast<char>(std::toupper(static_cast<unsigned char>(c))) : c);
        upper = false;
    }
    return out;
}

